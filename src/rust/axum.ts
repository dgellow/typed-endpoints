/**
 * An axum module from a contract.
 *
 * The generated module holds:
 *
 * - a serde type for every request part, response and declared error body
 * - `Handlers`: a trait with one method per operation. The application
 *   implements it in a module of its own; a method that no longer fits
 *   the routes does not compile
 * - an error enum per operation that declares errors, with one variant
 *   per status: a handler returns `Result<Response, Error>`, and a status
 *   the operation does not declare cannot be written
 * - `router(handlers)`: an `axum::Router` that checks each request
 *   against the contract's schema, calls the handler and checks what it
 *   returns
 *
 * @module
 */

import type {
  Contract,
  ContractOperation,
  JsonSchema,
} from "../contract/index.ts";
import { pascalCase, TypeGraph } from "../contract/types.ts";
import { constantCase, rawString, RustModels, snakeCase } from "./models.ts";
import { RUNTIME } from "./runtime.ts";

/** What the generated module needs to be told. */
export interface AxumOptions {
  /** Where the routes came from, for the module's documentation. */
  readonly source?: string;
}

/** One operation, with the Rust names the module gives its parts. */
interface Rendered {
  readonly operation: ContractOperation;
  /** Name of the handler method and of the route function. */
  readonly method: string;
  /** Prefix of the operation's constants. */
  readonly constant: string;
  readonly params?: string;
  readonly query?: string;
  readonly body?: string;
  readonly response?: string;
  /** Declared error bodies by status: their types. */
  readonly errors: ReadonlyMap<string, string>;
  /** Name of the error enum, when the operation declares errors. */
  readonly errorEnum?: string;
  /** The schemas the routes check against, by constant name. */
  readonly schemas: ReadonlyMap<string, JsonSchema>;
}

const RULE = "// " + "=".repeat(77);

/** `/files/{+path}` as axum writes it: `/files/{*path}`. */
function axumPath(path: string): string {
  return path.replace(/\{\+(\w+)\}/g, "{*$1}");
}

/**
 * Render a contract as the source of a Rust module.
 *
 * Operations that stream server-sent events are listed in a comment and
 * left out.
 */
export function renderAxum(
  contract: Contract,
  options: AxumOptions = {},
): string {
  const graph = new TypeGraph();
  const models = new RustModels(graph);
  const rendered: Rendered[] = [];
  const skipped: ContractOperation[] = [];

  for (const operation of contract.operations) {
    if (operation.events) {
      skipped.push(operation);
      continue;
    }
    const base = pascalCase(operation.operationId);
    const constant = constantCase(operation.operationId);
    const schemas = new Map<string, JsonSchema>();
    const part = (
      suffix: string,
      schema: JsonSchema | undefined,
      text: boolean,
    ): string | undefined => {
      if (!schema) return undefined;
      schemas.set(`${constant}_${constantCase(suffix)}`, schema);
      return models.type(graph.define(`${base}${suffix}`, schema, text));
    };

    // Path parameters without a schema are strings.
    const params = operation.params ??
      (operation.pathParams.length > 0
        ? {
          type: "object",
          properties: Object.fromEntries(
            operation.pathParams.map(({ name }) => [name, { type: "string" }]),
          ),
          required: operation.pathParams.map(({ name }) => name),
        }
        : undefined);

    const paramsType = part("Params", params, true);
    const queryType = part("Query", operation.query, true);
    const bodyType = part("Body", operation.body, false);
    const responseType = part("Response", operation.response, false);
    const errors = new Map(
      Object.entries(operation.errors ?? {}).map(([status, schema]) => [
        status,
        part(`Error${status}`, schema, false)!,
      ]),
    );

    rendered.push({
      operation,
      method: snakeCase(operation.operationId),
      constant,
      ...(paramsType && { params: paramsType }),
      ...(queryType && { query: queryType }),
      ...(bodyType && { body: bodyType }),
      ...(responseType && { response: responseType }),
      errors,
      ...(errors.size > 0 && { errorEnum: `${base}Error` }),
      schemas,
    });
  }

  const lines: string[] = [
    `//! API types, handlers and router${
      options.source ? ` for ${options.source}` : ""
    }.`,
    "//!",
    "//! Generated by typed-endpoints. Do not edit: implement [`Handlers`] in a",
    "//! module of your own and pass it to [`router`].",
    "",
    "#![allow(dead_code, unused_imports)]",
    "",
    RUNTIME,
    RULE,
    "// Types",
    RULE,
    "",
    ...models.render(),
    RULE,
    "// Schemas",
    RULE,
    "",
  ];

  for (const item of rendered) {
    for (const [name, schema] of item.schemas) {
      lines.push(
        `static ${name}_SCHEMA: LazyLock<Value> =`,
        `    LazyLock::new(|| schema(${rawString(JSON.stringify(schema))}));`,
      );
    }
  }

  lines.push("", RULE, "// Handlers", RULE, "");
  for (const item of rendered) lines.push(...errorEnum(item));
  lines.push(
    "/// One method per operation. A method returns the response value; for an",
    "/// operation that declares error responses, a `Result` whose error names",
    "/// the status.",
    "pub trait Handlers: Send + Sync + 'static {",
  );
  rendered.forEach((item, i) => {
    if (i > 0) lines.push("");
    lines.push(...handlerSignature(item));
  });
  lines.push("}");

  if (skipped.length > 0) {
    lines.push("", "// Not generated: server-sent event streams.");
    for (const operation of skipped) {
      lines.push(`//   ${operation.method} ${operation.path}`);
    }
  }

  lines.push("", RULE, "// Router", RULE, "");
  for (const item of rendered) lines.push(...route(item), "");
  lines.push(...router(rendered), "");

  return lines.join("\n");
}

/** What a handler returns: the response, or a `Result` with the errors. */
function returns(item: Rendered): string {
  const response = item.response ?? "()";
  return item.errorEnum ? `Result<${response}, ${item.errorEnum}>` : response;
}

function errorEnum(item: Rendered): string[] {
  if (!item.errorEnum) return [];
  const { operation } = item;
  return [
    `/// The error responses ${operation.method} ${operation.path} declares.`,
    "#[derive(Debug, Clone, PartialEq)]",
    `pub enum ${item.errorEnum} {`,
    ...[...item.errors].map(([status, type]) =>
      `    Status${status}(${type}),`
    ),
    "}",
    "",
  ];
}

/** The arguments a handler takes, in a fixed order. */
function handlerArguments(item: Rendered): string[] {
  return [
    ...(item.params ? [`params: ${item.params}`] : []),
    ...(item.query ? [`query: ${item.query}`] : []),
    ...(item.body ? [`body: ${item.body}`] : []),
  ];
}

function handlerSignature(item: Rendered): string[] {
  const { operation } = item;
  const summary = operation.summary ?? operation.description;
  return [
    `    /// ${operation.method} ${operation.path}${
      summary ? `: ${summary.split("\n")[0]}` : ""
    }`,
    `    fn ${item.method}(`,
    "        &self,",
    ...handlerArguments(item).map((argument) => `        ${argument},`),
    `    ) -> impl Future<Output = ${returns(item)}> + Send;`,
  ];
}

function route(item: Rendered): string[] {
  const { operation, constant } = item;
  const where = JSON.stringify(`${operation.method} ${operation.path}`);

  const extractors = ["State(handlers): State<Arc<H>>"];
  const parse: string[] = [];
  const passed: string[] = [];
  const read = (name: string, expression: string) =>
    parse.push(
      `    let ${name} = match ${expression} {`,
      "        Ok(value) => value,",
      "        Err(response) => return *response,",
      "    };",
    );

  if (item.params) {
    extractors.push("Path(path): Path<HashMap<String, String>>");
  }
  if (item.query) {
    extractors.push("Query(pairs): Query<Vec<(String, String)>>");
  }
  if (item.body) extractors.push("headers: HeaderMap", "bytes: Bytes");

  // In the order the TypeScript handlers check: body, query, path.
  if (item.body) {
    read("body", `body_of(&${constant}_BODY_SCHEMA, &headers, &bytes)`);
  }
  if (item.query) read("query", `query_of(&${constant}_QUERY_SCHEMA, pairs)`);
  if (item.params) {
    read("params", `params_of(&${constant}_PARAMS_SCHEMA, path)`);
  }
  if (item.params) passed.push("params");
  if (item.query) passed.push("query");
  if (item.body) passed.push("body");

  const call = `handlers.${item.method}(${passed.join(", ")}).await`;
  const success = item.response
    ? `respond(${where}, 200, Some(&${constant}_RESPONSE_SCHEMA), &value)`
    : "StatusCode::NO_CONTENT.into_response()";

  const answer = item.errorEnum
    ? [
      `    match ${call} {`,
      `        Ok(${item.response ? "value" : "()"}) => ${success},`,
      ...[...item.errors.keys()].map((status) =>
        `        Err(${item.errorEnum}::Status${status}(body)) => respond(${where}, ${status}, Some(&${constant}_${
          constantCase(`Error${status}`)
        }_SCHEMA), &body),`
      ),
      "    }",
    ]
    : item.response
    ? [`    let value = ${call};`, `    ${success}`]
    : [`    ${call};`, `    ${success}`];

  return [
    `async fn ${item.method}<H: Handlers>(`,
    ...extractors.map((extractor) => `    ${extractor},`),
    ") -> Response {",
    ...parse,
    ...answer,
    "}",
  ];
}

function router(rendered: readonly Rendered[]): string[] {
  // One route per path, with a method router for its operations.
  const byPath = new Map<string, Rendered[]>();
  for (const item of rendered) {
    const path = axumPath(item.operation.path);
    byPath.set(path, [...(byPath.get(path) ?? []), item]);
  }

  const lines = [
    "/// The operations as routes that call the given handlers.",
    "pub fn router<H: Handlers>(handlers: H) -> axum::Router {",
    "    axum::Router::new()",
  ];
  for (const [path, items] of byPath) {
    const [first, ...rest] = items.map((item) =>
      `${item.operation.method.toLowerCase()}(${item.method}::<H>)`
    );
    lines.push(
      `        .route(${JSON.stringify(path)}, axum::routing::${first}${
        rest.map((method) => `.${method}`).join("")
      })`,
    );
  }
  lines.push("        .with_state(Arc::new(handlers))", "}");
  return lines;
}
