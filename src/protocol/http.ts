/**
 * HTTP Executor for Protocol System
 *
 * Bridges protocol sessions with actual HTTP transport by using
 * generated route metadata to map operationIds to HTTP endpoints.
 */

import type { AnyStep, Protocol, RequestLocations } from "./types.ts";
import type { ExecutionContext, StepExecutor } from "./client.ts";
import { getNestedValue } from "./mapping.ts";

// =============================================================================
// Types
// =============================================================================

/** Route configuration - matches output from tsgen --format routes */
export interface RouteConfig {
  /** HTTP method. */
  readonly method: string;
  /** Path template with `{param}` placeholders, e.g. `/api/users/{id}`. */
  readonly path: string;
}

/** Configuration for the HTTP executor */
export interface HttpExecutorConfig<
  TRoutes extends Record<string, RouteConfig>,
> {
  /** Base URL for all API requests */
  readonly baseUrl: string;
  /**
   * Route metadata by operationId, as the route generators write it. Not
   * needed when every step knows its route (`fromEndpoint()` with `path`).
   */
  readonly routes?: TRoutes;
  /**
   * Steps this executor is not asked to perform, by name: they are handled
   * by another executor. They need no route.
   */
  readonly except?: readonly string[];
  /** Default headers to include with every request */
  readonly headers?: Record<string, string>;
  /** Custom fetch implementation (defaults to global fetch) */
  readonly fetch?: typeof fetch;
  /** Auth token propagation from previous step responses */
  readonly auth?: {
    /** Step name to extract token from */
    fromStep: string;
    /** Path to token in response (e.g., "accessToken" or "data.token") */
    tokenPath: string;
    /** Header name (defaults to "Authorization") */
    headerName?: string;
    /** Header prefix (defaults to "Bearer ") */
    headerPrefix?: string;
  };
}

// =============================================================================
// HTTP Error
// =============================================================================

/** A step's HTTP request was answered with a status outside 200-299. */
export class HttpError extends Error {
  /**
   * Create the error.
   *
   * @param status HTTP status code.
   * @param statusText HTTP status text.
   * @param body Response body as text.
   */
  constructor(
    public readonly status: number,
    public readonly statusText: string,
    public readonly body: string,
  ) {
    super(`HTTP ${status}: ${statusText}`);
    this.name = "HttpError";
  }
}

// =============================================================================
// HTTP Executor
// =============================================================================

/**
 * Create an HTTP executor for a protocol.
 *
 * Maps protocol steps to HTTP endpoints using operationId to look up
 * route information from generated metadata.
 *
 * @example
 * ```typescript
 * import { apiRoutes } from "./api-routes.ts"; // Generated by tsgen
 *
 * const executor = createHttpExecutor(authProtocol, {
 *   baseUrl: "https://api.example.com",
 *   routes: apiRoutes,
 *   auth: {
 *     fromStep: "login",
 *     tokenPath: "accessToken",
 *   },
 * });
 *
 * const session = createSession(authProtocol, executor);
 * const { response } = await session.execute("login", { username: "alice", password: "secret" });
 * ```
 */
export function createHttpExecutor<
  TSteps extends Record<string, AnyStep>,
  TRoutes extends Record<string, RouteConfig>,
>(
  protocol: Protocol<string, TSteps>,
  config: HttpExecutorConfig<TRoutes>,
): StepExecutor {
  const fetchFn = config.fetch ?? fetch;

  // Every step is resolved now: a protocol that cannot be served fails
  // when the executor is created, not at its first request.
  const resolved = new Map<string, RouteConfig>();
  const unresolved: string[] = [];
  for (const [name, step] of Object.entries(protocol.steps)) {
    if (config.except?.includes(name)) continue;
    const routeId = step.operationId ?? name;
    const route = step.route ?? config.routes?.[routeId];
    if (route) resolved.set(name, route);
    else unresolved.push(`"${name}" (operationId: ${routeId})`);
  }
  if (unresolved.length > 0) {
    throw new Error(
      `No route found for step ${
        unresolved.join(", ")
      }. A step needs a route of its own (fromEndpoint() with \`path\`) or an entry in \`routes\` under its operationId.`,
    );
  }

  return {
    async execute(
      stepName: string,
      request: unknown,
      ctx: ExecutionContext,
    ): Promise<unknown> {
      const step = protocol.steps[stepName];

      if (!step) {
        throw new Error(`Unknown step: ${stepName}`);
      }

      const route = resolved.get(stepName);
      if (!route) {
        throw new Error(
          `Step "${stepName}" is listed in \`except\`: this executor does not perform it`,
        );
      }

      const { method, path } = route;
      const parts = splitRequest(
        stepName,
        method,
        path,
        request,
        step.requestLocations,
      );
      const url = config.baseUrl + parts.path + parts.query;

      // Build headers
      const headers: Record<string, string> = { ...config.headers };

      // Auto-inject auth token from previous step response
      if (config.auth) {
        const prevResponse = ctx.responses[config.auth.fromStep];
        if (prevResponse !== undefined) {
          const token = getNestedValue(prevResponse, config.auth.tokenPath);
          if (token !== undefined && token !== null) {
            const headerName = config.auth.headerName ?? "Authorization";
            const prefix = config.auth.headerPrefix ?? "Bearer ";
            headers[headerName] = prefix + String(token);
          }
        }
      }

      // Build request options
      const requestInit: RequestInit = { method, headers };

      if (parts.body !== undefined) {
        headers["Content-Type"] ??= "application/json";
        requestInit.body = JSON.stringify(parts.body);
      }

      // Execute request
      const response = await fetchFn(url, requestInit);

      // A step whose response is an outcome gets the status with the
      // body, and its declared error statuses as responses.
      const outcome = step.outcome;
      const { status } = response;

      if (!response.ok) {
        const text = await response.text();
        if (outcome?.errors.includes(status)) {
          let body: unknown = text;
          try {
            body = JSON.parse(text);
          } catch {
            // Not JSON: the text is the body.
          }
          return { ok: false, status, body };
        }
        throw new HttpError(status, response.statusText, text);
      }

      const wrap = (body: unknown) =>
        outcome ? { ok: true, status, body } : body;

      // Parse response
      const contentType = response.headers.get("content-type") ?? "";
      if (contentType.includes("application/json")) {
        return wrap(await response.json());
      }

      // Return empty object for no-content responses
      if (response.status === 204) {
        return wrap({});
      }

      // Return text for non-JSON responses
      return wrap({ text: await response.text() });
    },
  };
}

// =============================================================================
// Helpers
// =============================================================================

function hasRequestBody(method: string): boolean {
  return method !== "GET" && method !== "HEAD";
}

function appendQuery(params: URLSearchParams, key: string, value: unknown) {
  if (value === undefined || value === null) return;
  if (Array.isArray(value)) {
    for (const item of value) appendQuery(params, key, item);
  } else {
    params.append(
      key,
      typeof value === "object" ? JSON.stringify(value) : String(value),
    );
  }
}

/**
 * Split a step's flat request into the path, query string and body of an
 * HTTP request.
 *
 * Each field goes where the step's `requestLocations` says. A field that is
 * not listed there goes:
 * - into the path, if the route template has a `{parameter}` of that name
 * - otherwise into the JSON body, for methods that have one
 * - otherwise into the query string (GET and HEAD)
 *
 * @example
 * splitRequest("posts", "GET", "/users/{userId}/posts", { userId: "1", limit: 5 })
 * // { path: "/users/1/posts", query: "?limit=5", body: undefined }
 */
function splitRequest(
  stepName: string,
  method: string,
  template: string,
  request: unknown,
  locations: RequestLocations | undefined,
): { path: string; query: string; body: unknown } {
  const withBody = hasRequestBody(method);
  const pathKeys = [...template.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);

  const isRecord = typeof request === "object" && request !== null &&
    !Array.isArray(request);
  if (!isRecord) {
    // Not an object of fields: it can only be the body.
    if (pathKeys.length > 0) {
      throw new Error(
        `Step "${stepName}": ${method} ${template} has path parameters, but the request is not an object`,
      );
    }
    return {
      path: template,
      query: "",
      body: withBody ? request : undefined,
    };
  }

  const fields = request as Record<string, unknown>;
  const query = new URLSearchParams();
  const body: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(fields)) {
    const targets = locations?.[key] ??
      [pathKeys.includes(key) ? "path" : withBody ? "body" : "query"];
    if (targets.includes("query")) appendQuery(query, key, value);
    if (targets.includes("body")) body[key] = value;
  }

  const path = template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = fields[key];
    if (value === undefined || value === null) {
      throw new Error(
        `Step "${stepName}": the request has no value for path parameter "${key}" of ${method} ${template}`,
      );
    }
    return encodeURIComponent(String(value));
  });

  const queryString = query.toString();
  return {
    path,
    query: queryString ? `?${queryString}` : "",
    body: withBody ? body : undefined,
  };
}
