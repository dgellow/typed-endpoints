class AsyncClient:
    """The operations as coroutines.

    A plain call returns the parsed response and raises `ApiError` for a status outside
    200-299. `_result` returns a declared error as a `Fail`. `_pages` and `_items`
    follow a paginated list to its end.
    """

    def __init__(
        self,
        base_url: str,
        *,
        http: httpx.AsyncClient | None = None,
        headers: Mapping[str, str] | None = None,
    ) -> None:
        """Send requests to `base_url`, with `http` if it is given.

        A client that is given its `http` leaves it open when it is closed:
        it belongs to whoever made it.
        """
        self._base_url = base_url.rstrip("/")
        self._owns_http = http is None
        self._http = http if http is not None else httpx.AsyncClient()
        self._headers = dict(headers or {})

    async def aclose(self) -> None:
        """Close the HTTP client, if this client made it."""
        if self._owns_http:
            await self._http.aclose()

    async def __aenter__(self) -> Self:
        """Use the client in a `with` statement, which closes it."""
        return self

    async def __aexit__(
        self,
        kind: type[BaseException] | None,
        error: BaseException | None,
        traceback: TracebackType | None,
    ) -> None:
        """Close the client."""
        await self.aclose()

    async def _send(
        self,
        method: str,
        path: str,
        query: Mapping[str, Any] | None = None,
        body: object = None,
    ) -> httpx.Response:
        return await self._http.request(
            method,
            self._base_url + path,
            params=query or None,
            json=body,
            headers=self._headers,
        )

