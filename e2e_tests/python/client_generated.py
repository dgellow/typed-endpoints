class AsyncClient:
    """The operations as coroutines.

    A plain call returns the parsed response and raises `ApiError` for a
    status outside 200-299. `_result` returns a declared error as a `Fail`.
    `_pages` and `_items` follow a paginated list to its end.
    """

    def __init__(
        self,
        base_url: str,
        *,
        http: httpx.AsyncClient | None = None,
        headers: Mapping[str, str] | None = None,
    ) -> None:
        self._base_url = base_url.rstrip("/")
        self._http = http if http is not None else httpx.AsyncClient()
        self._headers = dict(headers or {})

    async def aclose(self) -> None:
        await self._http.aclose()

    async def _send(
        self,
        method: str,
        path: str,
        query: Mapping[str, Any] | None = None,
        body: Any = None,
    ) -> httpx.Response:
        return await self._http.request(
            method,
            self._base_url + path,
            params=query or None,
            json=body,
            headers=self._headers,
        )

    async def _pages(
        self,
        call: str,
        method: str,
        path: str,
        query: dict[str, Any],
        meta: Mapping[str, Any],
    ) -> AsyncIterator[Any]:
        """Every page of a list, as parsed JSON."""
        url: str | None = None
        size: int | None = None
        while True:
            if url is None:
                response = await self._send(method, path, query)
            else:
                response = await self._http.request(method, url, headers=self._headers)
            if not response.is_success:
                raise ApiError(response.status_code, _content(response))
            page = _content(response)
            yield page
            if size is None:
                size = len(_page_items(page, meta))
            step = _next_page(call, meta, page, query, size)
            if step is None:
                return
            if step[0] == "query":
                query = step[1]
            else:
                url = _same_origin(call, self._base_url, step[1])

